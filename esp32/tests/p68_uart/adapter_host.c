static void setup_master(void)
{
    assert(tivoo_uart_transport_start()==ESP_OK);
    uart_link_tick(&s->link,0);
    uint64_t tok=s->link.token;
    incoming(UW_HELLO_ACK,tok,0,0,NULL,0);
    uint8_t p[8]={2,1,1,2,3,4,5,6};
    incoming(UW_STATUS,tok,0,0,p,8);
    assert(!strcmp(last_event,"spp_connected") && !memcmp(last_peer,p+2,6));
    small_clear();
}
static void ack_current(void)
{
    uart_wire_packet_t p;
    assert(xQueueReceive(s->data_queue,&p,0));
    uint8_t ok=0;
    incoming(UW_ACK,s->link.token,p.seq,p.epoch,&ok,1);
}
static void test_master(void)
{
    setup_master();
    assert(tivoo_uart_client_open());ack_current();
    uint32_t first=s->epoch;uint8_t code=6;
    /* Actual S3 reverse ring holds 8192 bytes; pending UART packet not ACKed
     * until the real TCP send drains enough space. */
    int sockets[2];assert(socketpair(AF_UNIX,SOCK_STREAM,0,sockets)==0);
    tivoo_control_client_connected(sockets[0]);
    uint8_t data[8192];memset(data,0x5a,sizeof(data));
    incoming(UW_REVERSE,s->link.token,1,first,data,4608);
    incoming(UW_REVERSE,s->link.token,2,first,data,3584);
    assert(tivoo_control_reverse_peak()==8192);
    assert(small_has(UW_ACK,first,0));
    incoming(UW_REVERSE,s->link.token,3,first,data,1);
    assert(s->link.pending && !small_has(UW_ACK,first,0));
    const uint8_t mac[6]={1,2,3,4,5,6};
    assert(tivoo_spp_queue_connect(mac));
    assert(s->link.outstanding);
    assert(tivoo_control_client_send_pending(sockets[0]));
    uint8_t received[512];assert(recv(sockets[1],received,sizeof(received),MSG_WAITALL)==512);
    assert(!memcmp(received,data,512));
    uart_link_tick(&s->link,now_ms());
    assert(!s->link.pending && small_has(UW_ACK,first,0) && s->link.outstanding);
    ack_current();
    tivoo_control_client_disconnected(sockets[0]);
    close(sockets[0]);close(sockets[1]);
    incoming(UW_ERROR,s->link.token,0,first,&code,1);
    assert(!tivoo_uart_client_valid());
    tivoo_uart_client_close();ack_current();
    assert(tivoo_uart_client_open());ack_current();
    uint32_t second=s->epoch;
    incoming(UW_ERROR,s->link.token,0,first,&code,1);
    assert(tivoo_uart_client_valid());
    code=3;incoming(UW_ERROR,s->link.token,0,first,&code,1);
    assert(tivoo_uart_client_valid());
    incoming(UW_ERROR,s->link.token,0,second,&code,1);
    assert(!tivoo_uart_client_valid());
    unsigned before=notifications;
    uint64_t old=s->link.token;
    uart_link_invalidate(&s->link);
    assert(!strcmp(last_event,"spp_disconnected") && notifications==before+1);
    s->link.token=old+1;
    incoming(UW_HELLO_ACK,s->link.token,0,0,NULL,0);
    uint8_t p[8]={2,1,1,2,3,4,5,6};
    incoming(UW_STATUS,s->link.token,0,0,p,8);
    assert(!strcmp(last_event,"spp_connected") && notifications==before+2);
    incoming(UW_STATUS,s->link.token,0,0,p,8);
    assert(notifications==before+2);

    /* A full 7778 diagnostics queue may reject the offline notification;
     * the same physical peer still requires fresh recovery publication. */
    reject_status_event=true;
    old=s->link.token;
    uart_link_invalidate(&s->link);
    tivoo_spp_link_state_t state;bool valid;
    tivoo_spp_get_status(&state,NULL,&valid);
    assert(state==TIVOO_SPP_LINK_DISCONNECTED && !valid);
    assert(notifications==before+2);
    reject_status_event=false;
    s->link.token=old+1;
    incoming(UW_HELLO_ACK,s->link.token,0,0,NULL,0);
    incoming(UW_STATUS,s->link.token,0,0,p,8);
    assert(!strcmp(last_event,"spp_connected") && notifications==before+3);
}
